// node scripts/compile-variant-tailwind.mjs <source dir> <globals.css> <out.css> <layer name>
//
// Compiles a generation's Tailwind utilities with the generation's own @theme and writes them to <out.css>,
// for sources whose pages lean on custom theme tokens (bg-ink, text-soft, animate-float, ...).
//
// Why: scope-variant-css.mjs strips each source's `@import "tailwindcss"` and `@theme`, so the gallery's
// Tailwind compiles every source's classes against the gallery's theme, and utilities built on the source's
// own tokens come out missing. Writing only those utilities back out by hand puts them in a different
// stylesheet from the rest, and since the scope adds no specificity, stylesheet order then decides between,
// say, the source's `text-ink` and the gallery's `md:text-white`.
//
// So this compiles the whole utility set the source uses, in Tailwind's own order, and wraps it in one cascade
// layer named <layer name>. The layer is declared after the gallery's own layers, so within this generation it
// outranks the gallery's copies of the same utilities, while unlayered CSS (CSS modules, the scoped globals)
// still beats it, as in the source. Preflight (Tailwind's base layer) is left out: the gallery already applies
// the same one. `@property` and `@keyframes` stay at the top level, where they have to be, and `animation`
// values that read an --animate-* theme variable are written out in full so scope-variant-css.mjs can rename
// the keyframes they use. scope-variant-css.mjs then scopes <out.css> like any other source stylesheet.
import fs from "node:fs/promises";
import path from "node:path";
import postcss from "postcss";
import { compile, optimize } from "@tailwindcss/node";
import { Scanner } from "@tailwindcss/oxide";

const [sourceDir, globalsPath, outPath, layerName] = process.argv.slice(2);
if (!sourceDir || !globalsPath || !outPath || !layerName) {
  console.error("usage: node scripts/compile-variant-tailwind.mjs <source dir> <globals.css> <out.css> <layer name>");
  process.exit(1);
}

// Only the Tailwind import and the theme blocks: the rest of globals.css is scoped separately as it is.
const globals = postcss.parse(await fs.readFile(globalsPath, "utf8"));
const themeOnly = postcss.root();
globals.each((node) => {
  if (node.type === "atrule" && (node.name === "theme" || (node.name === "import" && /tailwindcss/.test(node.params)))) {
    themeOnly.append(node.clone());
  }
});
const input = themeOnly.toString().replace(/@import\s+["']tailwindcss["'];?/, '@import "tailwindcss/theme.css" layer(theme);\n@import "tailwindcss/utilities.css" layer(utilities);');

const base = path.resolve(sourceDir);
const compiler = await compile(input, { base, onDependency() {} });
const scanner = new Scanner({ sources: [{ base, pattern: "**/*.{ts,tsx}", negated: false }] });
const candidates = scanner.scan();
const css = optimize(compiler.build(candidates), { minify: false }).code;

const root = postcss.parse(css);
const animateVars = new Map();
root.walkDecls(/^--animate-/, (decl) => animateVars.set(decl.prop, decl.value));
root.walkDecls(/^animation(-name)?$/, (decl) => {
  decl.value = decl.value.replace(/var\((--animate-[\w-]+)\)/g, (match, name) => animateVars.get(name) ?? match);
});

// Theme variables go on the source's <html> stand-in, not :root. The scoper would turn :root into the gallery's
// outer wrapper, above the [data-source-html] div where next/font sets its variables, so an alias such as
// --font-mono: var(--font-geist-mono) would resolve there to nothing.
root.walkRules((rule) => {
  if (rule.selector.replace(/\s+/g, "") === ":root,:host") rule.selector = "[data-source-html]";
});

const layer = postcss.atRule({ name: "layer", params: layerName });
const topLevel = [];
root.each((node) => {
  if (node.type === "atrule" && (node.name === "property" || node.name.endsWith("keyframes"))) {
    topLevel.push(node.clone());
  } else if (node.type === "atrule" && node.name === "layer" && !node.nodes) {
    // drop `@layer theme, base, ...;` order statements; the gallery's own CSS declares those
  } else {
    layer.append(node.clone());
  }
});

const header = `/* Generated by scripts/compile-variant-tailwind.mjs from ${path.relative(process.cwd(), globalsPath)}
   and the classes in ${path.relative(process.cwd(), sourceDir)}. Do not edit by hand; rerun the script. */\n`;
const out = postcss.root();
out.append(layer);
topLevel.forEach((node) => out.append(node));
await fs.writeFile(outPath, header + out.toString() + "\n");
console.log(`${candidates.length} candidates -> ${outPath} (${(await fs.stat(outPath)).size} bytes)`);
